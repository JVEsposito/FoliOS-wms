    /** Rectángulos de tinta, comunes a PDF, NiceLabel y ZPL. */
    public static function rectangulos(array $caja): array
    {
        $rectangulos = [];
        $sx = $caja['ancho'] / self::ANCHO;
        $sy = $caja['alto'] / self::ALTO;
        foreach (self::FILAS as $y => $fila) {
            $bytes = hex2bin($fila);
            $inicio = null;
            for ($x = 0; $x <= self::ANCHO; $x++) {
                $tinta = $x < self::ANCHO && (ord($bytes[intdiv($x, 8)]) & (1 << (7 - $x % 8))) !== 0;
                if ($tinta && $inicio === null) {
                    $inicio = $x;
                } elseif (! $tinta && $inicio !== null) {
                    $rectangulos[] = ['x' => $caja['x'] + $inicio * $sx, 'y' => $caja['y'] + $y * $sy,
                        'ancho' => ($x - $inicio) * $sx, 'alto' => $sy];
                    $inicio = null;
                }
            }
        }

        return $rectangulos;
    }

    public static function datos(): string
    {
        return hex2bin(implode('', self::FILAS));
    }

    /** Raster térmico con giro de 90° cuando el papel pasa por un cabezal de 100 mm. */
    public static function raster(int $ancho, int $alto, bool $girar): array
    {
        $origen = self::datos();
        $w = $girar ? $alto : $ancho;
        $h = $girar ? $ancho : $alto;
        $filaBytes = (int) ceil($w / 8);
        $datos = '';
        for ($y = 0; $y < $h; $y++) {
            $fila = array_fill(0, $filaBytes, 0);
            for ($x = 0; $x < $w; $x++) {
                $sx = (int) floor(($girar ? $y : $x) * self::ANCHO / $ancho);
                $sy = (int) floor(($girar ? $alto - 1 - $x : $y) * self::ALTO / $alto);
                if ((ord($origen[$sy * intdiv(self::ANCHO, 8) + intdiv($sx, 8)]) & (1 << (7 - $sx % 8))) !== 0) {
                    $fila[intdiv($x, 8)] |= 1 << (7 - $x % 8);
                }
            }
            $datos .= pack('C*', ...$fila);
        }

        return ['hex' => strtoupper(bin2hex($datos)), 'bytes_fila' => $filaBytes, 'bytes' => strlen($datos)];
    }
